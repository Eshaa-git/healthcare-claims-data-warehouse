"""Generate raw and stage table DDL from config/contracts.yaml and config/field_mapping.yaml.

The generated SQL is committed as migrations/002_raw_tables.sql and 003_stage_tables.sql;
tests/unit/test_ddl.py fails if the committed files drift from the configuration.
"""

from __future__ import annotations

from .config import contracts, field_mapping

RAW_TABLES = {
    "beneficiary_summary": "raw.beneficiary_summary",
    "inpatient_claims": "raw.inpatient_claims",
    "outpatient_claims": "raw.outpatient_claims",
    "drug_events": "raw.drug_events",
}

STAGE_TYPES = {
    "text": "text",
    "sex": "text",
    "date": "date",
    "money": "numeric(14,2)",
    "integer": "integer",
    "decimal": "numeric(14,3)",
    "flag_1yes_2no": "boolean",
    "esrd": "boolean",
}

HEADER = "-- Generated by `claims-dw generate-ddl` from config/; do not edit by hand.\n"


def raw_table_ddl() -> str:
    parts = [HEADER, "create schema if not exists raw;\n"]
    for dataset, spec in contracts().items():
        cols = [
            "    file_id bigint not null references ops.ingestion_files (file_id)",
            "    source_row_number bigint not null",
            "    run_id text not null",
            "    source_file text not null",
            "    loaded_at timestamptz not null default now()",
        ]
        cols += [f"    {c.lower()} text" for c in spec["columns"]]
        cols.append("    primary key (file_id, source_row_number)")
        parts.append(f"\ncreate table {RAW_TABLES[dataset]} (\n" + ",\n".join(cols) + "\n);\n")
    return "".join(parts)


def stage_columns(dataset: str) -> list[str]:
    """Stage column names in table order (excluding lineage columns)."""
    spec = field_mapping()[dataset]
    cols = [f["target"] for f in spec["fields"]]
    if spec.get("year_from_source_config"):
        cols.insert(1, "year")
    return cols


def stage_key(dataset: str) -> list[str]:
    spec = field_mapping()[dataset]
    key = [f["target"] for f in spec["fields"] if f.get("key")]
    if spec.get("year_from_source_config"):
        key.append("year")
    return key


def stage_table_ddl() -> str:
    parts = [HEADER, "create schema if not exists stage;\n"]
    for dataset, spec in field_mapping().items():
        cols = []
        for f in spec["fields"]:
            not_null = " not null" if f["nulls"] == "reject" else ""
            cols.append(f"    {f['target']} {STAGE_TYPES[f['type']]}{not_null}")
            if spec.get("year_from_source_config") and f["target"] == "beneficiary_id":
                cols.append("    year integer not null")
        cols += [
            "    file_id bigint not null references ops.ingestion_files (file_id)",
            "    source_row_number bigint not null",
            "    row_hash text not null",
            "    run_id text not null",
            "    loaded_at timestamptz not null default now()",
            f"    primary key ({', '.join(stage_key(dataset))})",
        ]
        table = spec["stage_table"]
        parts.append(f"\ncreate table {table} (\n" + ",\n".join(cols) + "\n);\n")
        parts.append(f"create index on {table} (file_id);\n")
    return "".join(parts)
