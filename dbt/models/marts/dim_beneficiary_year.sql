-- Grain: one beneficiary per source year. Claims join here on (beneficiary_id, claim year).
select
    beneficiary_year_key,
    beneficiary_id,
    year,
    birth_date,
    death_date,
    year - extract(year from birth_date)::int as age_at_year_end,
    death_date is not null and extract(year from death_date)::int = year as died_in_year,
    sex_code,
    case sex_code when '1' then 'male' when '2' then 'female' end as sex,
    race_code,
    has_esrd,
    state_code,
    county_code,
    part_a_coverage_months,
    part_b_coverage_months,
    hmo_coverage_months,
    part_d_coverage_months,
    cc_alzheimers,
    cc_heart_failure,
    cc_chronic_kidney,
    cc_cancer,
    cc_copd,
    cc_depression,
    cc_diabetes,
    cc_ischemic_heart,
    cc_osteoporosis,
    cc_ra_oa,
    cc_stroke_tia,
    ip_medicare_reimbursement_amt,
    op_medicare_reimbursement_amt,
    carrier_medicare_reimbursement_amt
from {{ ref('stg_beneficiary_year') }}
